def sheen(centre_x):
    return {(x, y) for x, y in band((centre_x, 22.5), (11.5, 9.5), 1.3) if y <= CROWN_ROW}


def layers():
    drawn = {direction: painted(clumps, sheen(centre)) for direction, (clumps, centre) in DRAWN.items()}

    return {**drawn, **{direction: [row[::-1] for row in drawn[source]] for direction, source in MIRRORS.items()}}


def main():
    for direction, rows in layers().items():
        write_grid(OUT / f'{direction}.txt', rows)


if __name__ == '__main__':
    main()
